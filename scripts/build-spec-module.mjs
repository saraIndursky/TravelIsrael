// Turns docs/TravelIsrael-spec.html into lib/generated/spec-html.ts so the private spec route
// can serve it without reading files at runtime. Run after editing the spec:
//   node scripts/build-spec-module.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const html = readFileSync("docs/TravelIsrael-spec.html", "utf8");
mkdirSync("lib/generated", { recursive: true });
writeFileSync(
  "lib/generated/spec-html.ts",
  `// Generated by scripts/build-spec-module.mjs from docs/TravelIsrael-spec.html. Do not edit by hand.\nexport const SPEC_HTML: string = ${JSON.stringify(html)};\n`
);
console.log("lib/generated/spec-html.ts written,", Math.round(html.length / 1024), "KB");
